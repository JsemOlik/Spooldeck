/**
 * Reads filament usage from sliced G-code, in the browser (before upload) and on the server (API).
 *
 * PrusaSlicer writes the stats as comments near the end of a plain .gcode file
 * ("; filament used [g] = 12.34, 0.00"), followed by the full config block. Binary .bgcode
 * (the default for the MK4, XL and MINI) keeps the same keys in metadata blocks at the start
 * of the file, so we only ever read a small part of either kind.
 * Spec: https://github.com/prusa3d/libbgcode/blob/main/doc/specifications.md
 */

export type SlicedFilament = {
  /** 0-based extruder / MMU slot. */
  index: number;
  /** As calculated by the slicer; null when its profile had no density. */
  grams: number | null;
  /** Filament volume, used to estimate grams from a spool's material density when grams is null. */
  cm3: number | null;
  mm: number | null;
  type: string | null;
  colorHex: string | null;
  /** The slicer's filament profile, e.g. "Prusament PLA Galaxy Black @MK4". */
  profile: string | null;
};

export type SliceInfo = {
  format: "gcode" | "bgcode";
  slicer: string | null;
  printName: string;
  printTime: string | null;
  /** Only filaments the print actually uses. */
  filaments: SlicedFilament[];
};

export class SlicerParseError extends Error {}

const ASCII_TAIL_BYTES = 1024 * 1024;
const ASCII_HEAD_BYTES = 4096;
const BGCODE_MAGIC = "GCDE";

export async function parseSlicedFile(file: Blob, fileName: string): Promise<SliceInfo> {
  const magic = new TextDecoder().decode(await file.slice(0, 4).arrayBuffer());
  const { meta, format } =
    magic === BGCODE_MAGIC ? { meta: await readBgcodeMetadata(file), format: "bgcode" as const } : { meta: await readGcodeMetadata(file), format: "gcode" as const };
  return sliceInfoFromMetadata(meta, format, fileName);
}

/** Collects "; key = value" comments from the start and end of a plain G-code file. */
async function readGcodeMetadata(file: Blob) {
  const head = await file.slice(0, ASCII_HEAD_BYTES).text();
  const tail = await file.slice(Math.max(0, file.size - ASCII_TAIL_BYTES)).text();
  const meta = parseGcodeComments(tail);
  const generatedBy = /^;\s*generated by (.+?)(?: on \d{4}-.*)?$/im.exec(head);
  if (generatedBy) meta.producer = generatedBy[1].trim();
  return meta;
}

export function parseGcodeComments(text: string): Record<string, string> {
  const meta: Record<string, string> = {};
  for (const m of text.matchAll(/^;\s*([a-z][\w ()[\]]*?)\s*=\s*(.*?)\s*$/gim)) meta[m[1]] = m[2];
  return meta;
}

// Block types and compression ids from the spec.
const BLOCK_GCODE = 1;
const BLOCK_THUMBNAIL = 5;
const COMPRESSION_NONE = 0;
const COMPRESSION_DEFLATE = 1;

/** Walks the metadata blocks of a binary G-code file and merges their INI key=value pairs. */
async function readBgcodeMetadata(file: Blob) {
  const header = new DataView(await file.slice(0, 10).arrayBuffer());
  if (header.byteLength < 10) throw new SlicerParseError("This .bgcode file is cut off.");
  const checksumSize = header.getUint16(8, true) === 1 ? 4 : 0;

  const meta: Record<string, string> = {};
  let offset = 10;
  while (offset + 8 <= file.size) {
    const view = new DataView(await file.slice(offset, offset + 12).arrayBuffer());
    const type = view.getUint16(0, true);
    const compression = view.getUint16(2, true);
    const dataSize = compression === COMPRESSION_NONE ? view.getUint32(4, true) : view.getUint32(8, true);
    const headerSize = compression === COMPRESSION_NONE ? 8 : 12;
    const paramsSize = type === BLOCK_THUMBNAIL ? 6 : 2;
    // Skip G-code and thumbnails without reading them. Metadata usually comes first, but the
    // spec doesn't promise it, so keep walking the block headers to the end.
    if (type !== BLOCK_GCODE && type !== BLOCK_THUMBNAIL) {
      const start = offset + headerSize + paramsSize;
      const data = new Uint8Array(await file.slice(start, start + dataSize).arrayBuffer());
      const text = await decompress(data, compression);
      if (text != null) {
        for (const line of text.split("\n")) {
          const eq = line.indexOf("=");
          if (eq > 0) meta[line.slice(0, eq).trim()] = line.slice(eq + 1).trim();
        }
      }
    }
    offset += headerSize + paramsSize + dataSize + checksumSize;
  }
  if (meta.Producer) meta.producer = meta.Producer;
  return meta;
}

async function decompress(data: Uint8Array, compression: number): Promise<string | null> {
  if (compression === COMPRESSION_NONE) return new TextDecoder().decode(data);
  // PrusaSlicer only uses Heatshrink for G-code blocks, which we never read.
  if (compression !== COMPRESSION_DEFLATE) return null;
  const stream = new Blob([data as BlobPart]).stream().pipeThrough(new DecompressionStream("deflate"));
  return new Response(stream).text();
}

/** Splits per-extruder strings: "PLA;PETG" or '"Name A";"Name B"' (names may contain ";" inside quotes). */
export function splitList(value: string | undefined): string[] {
  if (value == null || value === "") return [];
  const out: string[] = [];
  let current = "";
  let quoted = false;
  for (let i = 0; i < value.length; i++) {
    const c = value[i];
    if (quoted && c === "\\" && i + 1 < value.length) current += value[++i];
    else if (c === '"') quoted = !quoted;
    else if (c === ";" && !quoted) {
      out.push(current.trim());
      current = "";
    } else current += c;
  }
  out.push(current.trim());
  return out;
}

/** Splits per-extruder numbers: "1.76, 0.00" or "1.75,1.75". */
function numbers(value: string | undefined) {
  if (value == null || value === "") return [];
  return value.split(",").map((v) => {
    const n = Number(v.trim());
    return Number.isFinite(n) ? n : null;
  });
}

const positive = (n: number | null | undefined) => (n != null && n > 0 ? n : null);

export function sliceInfoFromMetadata(meta: Record<string, string>, format: SliceInfo["format"], fileName: string): SliceInfo {
  const grams = numbers(meta["filament used [g]"]);
  const mm = numbers(meta["filament used [mm]"]);
  const cm3 = numbers(meta["filament used [cm3]"]);
  if (!grams.length && !mm.length) {
    throw new SlicerParseError(
      "Couldn't find filament usage in this file. Export the G-code from PrusaSlicer (plain .gcode or binary .bgcode) and upload that.",
    );
  }

  const diameters = numbers(meta.filament_diameter);
  const types = splitList(meta.filament_type);
  const profiles = splitList(meta.filament_settings_id);
  const extruderColours = splitList(meta.extruder_colour);
  const filamentColours = splitList(meta.filament_colour);

  const count = Math.max(grams.length, mm.length);
  const filaments: SlicedFilament[] = [];
  for (let i = 0; i < count; i++) {
    const length = positive(mm[i]);
    const diameter = diameters[i] ?? diameters[0] ?? 1.75;
    const volume = positive(cm3[i]) ?? (length != null ? (Math.PI * (diameter / 2) ** 2 * length) / 1000 : null);
    const g = positive(grams[i]);
    if (g == null && volume == null) continue;
    filaments.push({
      index: i,
      grams: g == null ? null : round2(g),
      cm3: volume == null ? null : round2(volume),
      mm: length,
      type: types[i] || types[0] || null,
      // The extruder colour is what PrusaSlicer shows for MMU prints; fall back to the profile colour.
      colorHex: hex(extruderColours[i]) ?? hex(filamentColours[i]),
      profile: profiles[i] || null,
    });
  }
  if (!filaments.length) throw new SlicerParseError("This file doesn't use any filament.");

  return {
    format,
    slicer: meta.producer?.replace(/\+\S*$/, "") || null,
    printName: printNameFromFile(fileName),
    printTime: meta["estimated printing time (normal mode)"] || null,
    filaments,
  };
}

function hex(value: string | undefined) {
  return value && /^#[0-9a-f]{6}$/i.test(value) ? value.toLowerCase() : null;
}

const round2 = (n: number) => Math.round(n * 100) / 100;

/** "Cable_clip_0.4n_0.2mm_PETG_MK4_1h2m.bgcode" → "Cable clip": drops PrusaSlicer's default suffix. */
export function printNameFromFile(fileName: string) {
  const base = fileName.replace(/^.*[\\/]/, "").replace(/\.(b?gcode|gco|g)$/i, "");
  const name = base
    .replace(/_\d+(\.\d+)?n_\d+(\.\d+)?mm_.*$/i, "")
    .replace(/_/g, " ")
    .trim();
  return (name || base).slice(0, 200);
}
