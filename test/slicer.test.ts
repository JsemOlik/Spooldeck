import { describe, expect, test } from "bun:test";
import { gramsFor, type SpoolCandidate, suggestSpools } from "@/lib/slicer/match";
import { parseSlicedFile, printNameFromFile, type SlicedFilament, SlicerParseError, splitList } from "@/lib/slicer/parse";
import { parseSlicedStream } from "@/lib/slicer/stream";
import { bgcode } from "./fixtures/bgcode";

// The end of a PrusaSlicer 2.9 file for a two-colour MMU print: stats, then the config block.
const GCODE_FOOTER = `
G1 X10 Y10 E.5
M84 ; disable motors
; EXECUTABLE_BLOCK_END

; filament used [mm] = 3120.55, 412.30, 0.00
; filament used [cm3] = 7.51, 0.99, 0.00
; filament used [g] = 9.31, 0.00, 0.00
; filament cost = 0.23, 0.00, 0.00
; total filament used [g] = 9.31
; total filament cost = 0.23
; estimated printing time (normal mode) = 1h 12m 5s

; prusaslicer_config = begin
; extruder_colour = "";#2b2b2b;""
; filament_colour = #FF8000;#FFFFFF;#FF8000
; filament_density = 1.24,0,1.24
; filament_diameter = 1.75,1.75,1.75
; filament_settings_id = "Prusament PLA Galaxy Black @MMU3";"My \\"Silk\\" PETG; matte";"Generic PLA"
; filament_type = PLA;PETG;PLA
; prusaslicer_config = end
`;

const gcodeFile = (body: string) =>
  new Blob([`; generated by PrusaSlicer 2.9.2+linux-x64-GTK3 on 2025-03-01 at 10:00:00 UTC\nG28\n${"G1 X1 Y1\n".repeat(50)}${body}`]);

describe("parseSlicedFile", () => {
  test("reads per-extruder usage from plain G-code", async () => {
    const info = await parseSlicedFile(gcodeFile(GCODE_FOOTER), "Desk_tidy_0.4n_0.2mm_PLA,PETG_MK4S_1h12m.gcode");
    expect(info).toMatchObject({ format: "gcode", slicer: "PrusaSlicer 2.9.2", printName: "Desk tidy", printTime: "1h 12m 5s" });
    expect(info.filaments).toEqual([
      { index: 0, grams: 9.31, cm3: 7.51, mm: 3120.55, type: "PLA", colorHex: "#ff8000", profile: "Prusament PLA Galaxy Black @MMU3" },
      // Density 0 in the profile: no grams from the slicer, so Spooldeck estimates them from the volume.
      { index: 1, grams: null, cm3: 0.99, mm: 412.3, type: "PETG", colorHex: "#2b2b2b", profile: 'My "Silk" PETG; matte' },
    ]);
  });

  test("handles CRLF line endings", async () => {
    const info = await parseSlicedFile(gcodeFile(GCODE_FOOTER.replace(/\n/g, "\r\n")), "x.gcode");
    expect(info.filaments.map((f) => f.grams)).toEqual([9.31, null]);
  });

  test("falls back to length and diameter when there's no volume", async () => {
    const info = await parseSlicedFile(gcodeFile("; filament used [mm] = 1000\n; filament_diameter = 1.75\n"), "x.gcode");
    expect(info.filaments[0]).toMatchObject({ grams: null, cm3: 2.41, mm: 1000 });
  });

  test("rejects files without usage stats", async () => {
    await expect(parseSlicedFile(gcodeFile(";Filament used: 1.2m\n"), "cura.gcode")).rejects.toBeInstanceOf(SlicerParseError);
  });

  test("reads binary G-code, including deflated metadata and blocks after the G-code", async () => {
    const file = bgcode([
      { type: 0, text: "Producer=PrusaSlicer 2.9.2\n" },
      { type: 3, text: "printer_model=MK4S\nfilament_type=PETG\nextruder_colour=\"\"\nfilament used [mm]=995.33\nfilament used [g]=2.97\n" },
      { type: 5, size: 300 },
      { type: 1, size: 5000, deflate: false },
      { type: 4, deflate: true, text: "filament used [mm]=995.33\nfilament used [cm3]=2.39\nfilament used [g]=2.97\nestimated printing time (normal mode)=20m 38s\n" },
      { type: 2, deflate: true, text: "filament_colour=#00FF00\nfilament_settings_id=\"Prusament PETG Jet Black\"\n" },
    ]);
    const info = await parseSlicedFile(file, "box.bgcode");
    expect(info).toMatchObject({ format: "bgcode", slicer: "PrusaSlicer 2.9.2", printName: "box", printTime: "20m 38s" });
    expect(info.filaments).toEqual([
      { index: 0, grams: 2.97, cm3: 2.39, mm: 995.33, type: "PETG", colorHex: "#00ff00", profile: "Prusament PETG Jet Black" },
    ]);
  });

  test("reads binary G-code without checksums", async () => {
    const file = bgcode([{ type: 4, text: "filament used [g]=1.5\n" }, { type: 1, size: 100 }], false);
    expect((await parseSlicedFile(file, "a.bgcode")).filaments[0].grams).toBe(1.5);
  });
});

describe("helpers", () => {
  test("splitList keeps quoted names whole", () => {
    expect(splitList('"A; B";C;""')).toEqual(["A; B", "C", ""]);
    expect(splitList("PLA")).toEqual(["PLA"]);
    expect(splitList("")).toEqual([]);
  });

  test("printNameFromFile drops PrusaSlicer's default suffix", () => {
    expect(printNameFromFile("C:\\prints\\Cable_clip_0.4n_0.2mm_PETG_MK4_1h2m.bgcode")).toBe("Cable clip");
    expect(printNameFromFile("benchy.gcode")).toBe("benchy");
    expect(printNameFromFile("0.4n_0.2mm_PLA.gcode")).toBe("0.4n 0.2mm PLA");
  });
});

describe("suggestSpools", () => {
  const spool = (s: Partial<SpoolCandidate> & { id: number }): SpoolCandidate => ({
    status: "opened",
    remaining: 800,
    filamentName: "PLA",
    colorName: null,
    colorHex: null,
    brandName: null,
    materialName: "PLA",
    density: 1.24,
    ...s,
  });
  const sliced = (f: Partial<SlicedFilament>): SlicedFilament => ({
    index: 0,
    grams: 10,
    cm3: 8,
    mm: 3000,
    type: "PLA",
    colorHex: null,
    profile: null,
    ...f,
  });

  const shelf = [
    spool({ id: 1, brandName: "Prusament", filamentName: "PLA Galaxy Black", colorName: "Galaxy Black", colorHex: "#3d3e3d" }),
    spool({ id: 2, brandName: "Prusament", filamentName: "PLA Jet Black", colorName: "Jet Black", colorHex: "#141414" }),
    spool({ id: 3, brandName: "Generic", filamentName: "PETG White", materialName: "PETG", colorName: "White", colorHex: "#ffffff" }),
    spool({ id: 4, brandName: "Prusament", filamentName: "PLA Galaxy Black", colorName: "Galaxy Black", colorHex: "#3d3e3d", status: "sealed" }),
  ];

  test("matches by profile name and prefers opened spools", () => {
    expect(suggestSpools([sliced({ profile: "Prusament PLA Galaxy Black @MK4" })], shelf)).toEqual([1]);
  });

  test("matches by material and colour", () => {
    const result = suggestSpools(
      [sliced({ colorHex: "#151515" }), sliced({ index: 1, type: "PETG", colorHex: "#fafafa" })],
      shelf,
    );
    expect(result).toEqual([2, 3]);
  });

  test("never suggests one spool twice", () => {
    const f = sliced({ profile: "Prusament PLA Galaxy Black" });
    expect(suggestSpools([f, { ...f, index: 1 }], shelf)).toEqual([1, 4]);
  });

  test("leaves a filament unassigned when nothing fits", () => {
    expect(suggestSpools([sliced({ type: "ASA" })], shelf)).toEqual([null]);
  });

  test("gramsFor estimates from volume with the spool's density", () => {
    expect(gramsFor(sliced({ grams: null, cm3: 10 }), { density: 1.27 })).toBe(12.7);
    expect(gramsFor(sliced({ grams: null, cm3: 10 }), null)).toBe(12.4);
    expect(gramsFor(sliced({ grams: 3 }), { density: 2 })).toBe(3);
  });
});

describe("parseSlicedStream", () => {
  /** Streams a blob in small chunks and counts how much of it was read. */
  function chunked(blob: Blob, size = 1000) {
    const read = { bytes: 0 };
    let offset = 0;
    const stream = new ReadableStream<Uint8Array>({
      async pull(controller) {
        if (offset >= blob.size) return controller.close();
        const chunk = new Uint8Array(await blob.slice(offset, offset + size).arrayBuffer());
        offset += chunk.length;
        read.bytes = offset;
        controller.enqueue(chunk);
      },
    });
    return { stream, read };
  }

  test("reads a .bgcode only up to its G-code", async () => {
    const file = bgcode([
      { type: 0, text: "Producer=PrusaSlicer 2.9.2\n" },
      { type: 5, size: 20_000 },
      { type: 4, text: "filament used [g]=10.00, 4.00\n", deflate: true },
      { type: 1, size: 5_000_000 },
    ]);
    const { stream, read } = chunked(file);
    const info = await parseSlicedStream(stream, "Cube.bgcode");
    expect(info.filaments.map((f) => [f.index, f.grams])).toEqual([
      [0, 10],
      [1, 4],
    ]);
    expect(read.bytes).toBeLessThan(30_000);
  });

  test("keeps only the start and the end of plain G-code", async () => {
    const file = gcodeFile(`${"G1 X2 Y2 E.1\n".repeat(200_000)}${GCODE_FOOTER}`);
    expect(file.size).toBeGreaterThan(2_000_000);
    const info = await parseSlicedStream(chunked(file, 64 * 1024).stream, "big.gcode");
    expect(info).toMatchObject({ format: "gcode", slicer: "PrusaSlicer 2.9.2" });
    expect(info.filaments.map((f) => f.grams)).toEqual([9.31, null]);
  });

  test("reads a short file whole", async () => {
    const info = await parseSlicedStream(chunked(gcodeFile(GCODE_FOOTER), 7).stream, "x.gcode");
    expect(info.filaments).toHaveLength(2);
  });
});
